<h1>Over Shakka</h1>
<p>
	Shakka is een gratis app voor kiters in Nederland. Per spot zie je of je kunt kiten, je krijgt een
	melding als het gaat waaien, en je deelt met één link dat je gaat.
</p>
<h2>Hoe werkt het oordeel?</h2>
<p>
	Shakka combineert de windverwachting van meerdere weermodellen met het profiel van de spot: de
	windrichting ten opzichte van de kust, het getij, seizoensregels en daglicht. Bij aflandige of
	schuin aflandige wind is het oordeel altijd: niet gaan.
</p>
<h2>Spotgegevens</h2>
<p>
	De spotprofielen zijn met de hand samengesteld. Een spot die nog niet is gecontroleerd, staat
	gemarkeerd als niet geverifieerd. Check ter plekke altijd de lokale regels.
</p>
<h2>Geen advertenties, geen tracking</h2>
<p>Shakka heeft geen advertenties en gebruikt geen analytics of trackers van derden.</p>
