"""Generated JSON contracts (reason codes, direction classes, confidence) for the web app."""

import json
from collections.abc import Callable
from pathlib import Path
from typing import Final

from shakka.config import REPO_ROOT
from shakka.domain.consensus import CONFIDENCE_LABEL_NL, Confidence
from shakka.domain.direction import DIR_CLASS_LABEL_NL, RIDABLE_DIR_CLASSES, DirClass
from shakka.domain.evaluation import REASON_EFFECT, REASON_LABEL_NL, ReasonCode

CONTRACTS_DIR: Final[Path] = REPO_ROOT / "data" / "contracts"
CONTRACT_FILES: Final = ("reason_codes.json", "dir_classes.json", "confidence.json")
GENERATED_NOTE: Final = "Generated by `shakka contracts export` from shakka.domain. Do not edit."


def _text(items: list[dict[str, object]]) -> str:
    obj = {"_generated": GENERATED_NOTE, "items": items}
    return json.dumps(obj, ensure_ascii=False, indent=2) + "\n"


def build_contracts() -> dict[str, str]:
    """{file name: file text} for CONTRACT_FILES, in that order. Text is
    json.dumps(obj, ensure_ascii=False, indent=2) + "\n"."""
    reasons = [
        {"code": r.value, "effect": REASON_EFFECT[r].value, "label_nl": REASON_LABEL_NL[r]}
        for r in ReasonCode
    ]
    classes = [
        {
            "code": c.value,
            "ridable": c in RIDABLE_DIR_CLASSES,
            "label_nl": DIR_CLASS_LABEL_NL[c],
        }
        for c in DirClass
    ]
    confidence = [{"code": c.value, "label_nl": CONFIDENCE_LABEL_NL[c]} for c in Confidence]
    return {
        "reason_codes.json": _text(reasons),
        "dir_classes.json": _text(classes),
        "confidence.json": _text(confidence),
    }


def _status(directory: Path) -> dict[str, str]:
    """{name: 'ok' | 'stale' | 'missing'} for every contract file."""
    out: dict[str, str] = {}
    for name, text in build_contracts().items():
        path = directory / name
        if not path.is_file():
            out[name] = "missing"
        elif path.read_bytes() != text.encode("utf-8"):
            out[name] = "stale"
        else:
            out[name] = "ok"
    return out


def check_contracts(directory: Path | None = None) -> list[str]:
    """Names in CONTRACT_FILES that are missing or differ from build_contracts(); writes nothing.
    directory None -> CONTRACTS_DIR (looked up at call time)."""
    directory = CONTRACTS_DIR if directory is None else directory
    return [name for name, state in _status(directory).items() if state != "ok"]


def export_contracts(directory: Path | None = None) -> list[str]:
    """Create the directory if needed; write (UTF-8 bytes) only files whose text differs.
    Returns the names written. Other files in the directory are left alone."""
    directory = CONTRACTS_DIR if directory is None else directory
    directory.mkdir(parents=True, exist_ok=True)
    texts = build_contracts()
    written = []
    for name in check_contracts(directory):
        (directory / name).write_bytes(texts[name].encode("utf-8"))
        written.append(name)
    return written


def run_contracts_export(
    *, check: bool, echo: Callable[[str], None], directory: Path | None = None
) -> int:
    directory = CONTRACTS_DIR if directory is None else directory
    shown = "data/contracts"
    if check:
        status = _status(directory)
        for name, state in status.items():
            echo(f"{state:<7} {shown}/{name}")
        if all(s == "ok" for s in status.values()):
            echo("contracts export: check ok")
            return 0
        echo("contracts export: check failed; run 'shakka contracts export'")
        return 1
    written = set(export_contracts(directory))
    for name in CONTRACT_FILES:
        if name in written:
            echo(f"wrote   {shown}/{name}")
        else:
            echo(f"ok      {shown}/{name} (unchanged)")
    echo("contracts export: ok")
    return 0
